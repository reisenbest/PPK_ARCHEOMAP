// map_icons.js

// Иконка для памятников
const monumentIcon = L.icon({
  iconUrl: '../../media/icons/minimarker_red.png',  // путь к изображению
  iconSize: [10, 10],          // размер иконки
  iconAnchor: [0, 0],          // точка "якоря" иконки (куда указывает)
  popupAnchor: [0, 0]          // смещение всплывающего окна относительно иконки
});

// Статичный маркер Петропавловской крепости
// Для этого требуется, чтобы переменная map была уже определена, поэтому 
// в этот файл можно либо поместить только определение иконки, либо экспортировать
// функцию для добавления статичного маркера, вызвав её после инициализации карты.

// Если использовать просто этот код — map должен быть определён раньше!
function addStaticMonumentMarker(map) {
  L.marker([59.95, 30.3167], { icon: monumentIcon })
    .addTo(map)
    .bindPopup("Петропавловская крепость")
    .openPopup();
}